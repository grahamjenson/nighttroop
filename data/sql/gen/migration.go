const migrationTmpl = `// Code generated by migration.go; DO NOT EDIT.
package migrations

import (
	"context"
	"log/slog"
	"database/sql"
	"fmt"
)

func Migrate{{.Name}}(ctx context.Context, db *sql.DB) error {

	_, err := db.Exec("CREATE TABLE IF NOT EXISTS schema_migrations (version TEXT NOT NULL PRIMARY KEY);")
	if (err != nil) {
		return fmt.Errorf("failed to create schema_migrations table: %w", err)
	}
	


{{- range $index, $name := .GetFileVars }}
	if err := Migration{{$name}}(ctx, db); err != nil {
		return err
	}
{{- end}}
	return nil
}

{{range $index, $name := .GetFileVars }}
func Migration{{$name}}(ctx context.Context, db *sql.DB) error {

	var versionSeen int;
	err  := db.QueryRow("SELECT COUNT(version) FROM schema_migrations WHERE version = ?;", "{{$name}}").Scan(&versionSeen)
	if err != nil {
		return err
	}
	if versionSeen > 0 {
		slog.Info("Migration already applied, skipping", "migration", "{{$name}}")
		
		return nil
	}
	slog.Info("Migration applying", "migration", "{{$name}}")

	tx, err := db.BeginTx(ctx, nil)
	if err != nil {
		return fmt.Errorf("failed to begin transaction: %w", err)
	}
	defer tx.Rollback()
		
		{{- range $stmt := index $.MigrationStatements $index}}
			slog.Info("Migrating", "statement", ` + "`" + `{{$stmt.Header}}` + "`" + `)
			if _, err := tx.ExecContext(ctx, ` + "`" + `{{$stmt.Statement}}` + "`" + `); err != nil {
				return fmt.Errorf("failed to execute migration statement %s: %w", ` + "`" + `{{$stmt.Header}}` + "`" + `, err)
			}
		{{- end}}

	if _, err := tx.ExecContext(ctx, "INSERT INTO schema_migrations (version) VALUES (?);", "{{$name}}"); err != nil {
		return fmt.Errorf("failed to insert migration version: %w", err)
	}

	return tx.Commit()
}
{{end}}
`

type MigrationStatement struct {
	Statement string
	Header    string
}

func (c MigrationConfig) GetFileVars() []string {
	var vars []string
	for _, filevars := range c.Migrations {
		vars = append(vars, utils.SnakeToCapitalCamelCase(utils.FileToName(filevars)))
	}
	return vars
}

type MigrationConfig struct {
	Name                string
	Migrations          []string
	MigrationStatements [][]MigrationStatement
}

func BuildMigration(name string, migrations []string) error {
	if len(migrations) == 0 {
		return fmt.Errorf("At least one migration file is required")
	}

	for _, file := range migrations {
		if fileInfo, err := os.Stat(file); err != nil || fileInfo.IsDir() {
			return fmt.Errorf("invalid file: %s", file)
		}
	}

	migrationStatements := [][]MigrationStatement{}
	for _, file := range migrations {
		content, _ := os.ReadFile(file)
		statements := SeperateSQLStatements(string(content))

		migrationStatements = append(migrationStatements, statements)

	}

	config := MigrationConfig{
		Name:                utils.SnakeToCapitalCamelCase(name),
		Migrations:          migrations,
		MigrationStatements: migrationStatements,
	}

	outFilename := strings.TrimSuffix(strings.ToLower(name), ".sql")
	outputFolder := filepath.Dir(migrations[0])

	outputPath := filepath.Join(outputFolder, "z_"+outFilename+"_gen.go")
	f, _ := os.Create(outputPath)
	fmt.Println("Generated migration file: " + outputPath)
	defer f.Close()

	t := template.Must(template.New("migrations").Parse(migrationTmpl))

	err := t.Execute(f, config)
	if err != nil {
		return fmt.Errorf("failed to execute template: %w", err)
	}

	return exec.Command("go", "fmt", outputPath).Run()
}

func SeperateSQLStatements(sql string) []MigrationStatement {
	// Regex splits by semicolon followed by optional whitespace and newline
	re := regexp.MustCompile(`(?m);(\s*)$`)
	raw := re.Split(sql, -1)

	var cleaned []MigrationStatement
	for _, individualStatement := range raw {

		migrationStatemnet := createMigrationStatement(individualStatement)
		if migrationStatemnet != nil {
			cleaned = append(cleaned, *migrationStatemnet)
		}

	}
	return cleaned
}

func createMigrationStatement(statement string) *MigrationStatement {
	// If empty or only whitespace, skip
	individualStatement := strings.TrimSpace(statement)
	if individualStatement == "" {
		return nil
	}

	// remove all comment lines from the statment beginning with -- and trim the statement
	lines := strings.Split(individualStatement, "\n")
	var nonCommentLines []string
	for _, line := range lines {
		trimmed := strings.TrimSpace(line)
		if !strings.HasPrefix(trimmed, "--") && trimmed != "" {
			nonCommentLines = append(nonCommentLines, line)
		}
	}
	if len(nonCommentLines) == 0 {
		return nil
	}

	cleanedStatement := strings.Join(nonCommentLines, "\n")

	header := firstN(nonCommentLines[0], 50)
	return &MigrationStatement{Statement: cleanedStatement, Header: header}
}

func firstN(str string, n int) string {
	// Convert string to a slice of runes
	runes := []rune(str)

	// Check if the requested length 'n' is greater than or equal to the actual number of runes
	if n >= len(runes) {
		return str // Return the original string if it's shorter or equal to n
	}

	// Otherwise, slice the rune slice and convert it back to a string
	return string(runes[:n])
}
