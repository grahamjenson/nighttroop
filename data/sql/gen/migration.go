package gen

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"text/template"
)

const migrationTmpl = `// Code generated by migration.go; DO NOT EDIT.
package {{.PkgName}}

import (
	"database/sql"
	"embed"
	"errors"
	"log"

	_ "github.com/mattn/go-sqlite3"

	"github.com/golang-migrate/migrate/v4"
	"github.com/golang-migrate/migrate/v4/database/sqlite3"
	"github.com/golang-migrate/migrate/v4/source/iofs"
)

//go:embed migrations/*.sql
var migrations embed.FS

func MigrateUp(db *sql.DB) error {
	driver, err := sqlite3.WithInstance(db, &sqlite3.Config{})
	if err != nil {
		log.Fatal(err)
	}

	d, err := iofs.New(migrations, "migrations")
	if err != nil {
		log.Fatal(err)
	}

	m, err := migrate.NewWithInstance(
		"iofs",
		d,
		"sqlite3",
		driver,
	)
	if err != nil {
		log.Fatal(err)
	}

	err = m.Up()
	if err != nil && !errors.Is(err, migrate.ErrNoChange) {
		log.Fatal(err)
	}

	log.Println("migrations applied")

	return nil
}

func MigrateDown(db *sql.DB) error {
	driver, err := sqlite3.WithInstance(db, &sqlite3.Config{})
	if err != nil {
		log.Fatal(err)
	}

	d, err := iofs.New(migrations, "migrations")
	if err != nil {
		log.Fatal(err)
	}

	m, err := migrate.NewWithInstance(
		"iofs",
		d,
		"sqlite3",
		driver,
	)
	if err != nil {
		log.Fatal(err)
	}

	err = m.Down()
	if err != nil && !errors.Is(err, migrate.ErrNoChange) {
		log.Fatal(err)
	}

	log.Println("migrations rolled back")

	return nil
}
`

type MigrationConfig struct {
	PkgName string
}

func BuildMigration(folder string) error {

	config := MigrationConfig{
		PkgName: folder,
	}

	outputPath := filepath.Join(folder, "z_migrations_gen.go")
	f, _ := os.Create(outputPath)
	fmt.Println("Generated migration file: " + outputPath)
	defer f.Close()

	t := template.Must(template.New("migrations").Parse(migrationTmpl))

	err := t.Execute(f, config)
	if err != nil {
		return fmt.Errorf("failed to execute template: %w", err)
	}

	return exec.Command("go", "fmt", outputPath).Run()
}
