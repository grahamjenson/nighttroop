const dbTmpl = `// Code generated by migration.go; DO NOT EDIT.
package {{.PkgName}}

import (
	"context"
	"database/sql"
	"embed"
	"errors"
	"fmt"
	"log/slog"

	"nighttroop.t1d.nz/utils"
	"nighttroop.t1d.nz/utils/config"

	_ "modernc.org/sqlite"

	"github.com/golang-migrate/migrate/v4"
	"github.com/golang-migrate/migrate/v4/database/sqlite3"
	"github.com/golang-migrate/migrate/v4/source/iofs"
)


type DB struct{
	SQLiteDB  *sql.DB
	ServerConfig config.ServerConfig
	Queries *Queries
}

func NewDB(ctx context.Context, path string, cacheSize int, serverConfig config.ServerConfig) (*DB, error) {
	db := &DB{
		ServerConfig: serverConfig,
    }


	var err error
	var sqldb *sql.DB

	if serverConfig.IsTest() {
		sqldb, err = OpenInMemorySqliteDB()
	} else {
		sqldb, err = OpenSqliteDB(path, cacheSize)
	}
	if err != nil {
		return nil, fmt.Errorf("{{.PkgName}} db cannot open for: %s %w", path, err)
	}
	db.SQLiteDB = sqldb

	err = MigrateUp(sqldb)
	if err != nil {
		sqldb.Close()
		return db, fmt.Errorf("{{.PkgName}} Migration Error for: %s %w", path, err)
	}

	
	slog.Info("{{.PkgName}} Migration applied successfully to " + path)

	db.Queries, err = Prepare(ctx, sqldb)
	if err != nil {
		sqldb.Close()
		return db, fmt.Errorf("{{.PkgName}} Prepare Error for: %s %w", path, err)
	}
		
	return db, nil
}

func (db *DB) Name() string {
	return "{{.PkgName}}"
}

func (db *DB) MigrateDown() error {
	return MigrateDown(db.SQLiteDB)
}

func (db *DB) GetRawDB() *sql.DB {
	return db.SQLiteDB
}

func (db *DB) Close() error {
	return db.SQLiteDB.Close()
}
	
//go:embed migrations/*.sql
var migrations embed.FS

func MigrateUp(db *sql.DB) error {
	driver, err := sqlite3.WithInstance(db, &sqlite3.Config{})
	if err != nil {
		return err
	}

	d, err := iofs.New(migrations, "migrations")
	if err != nil {
		return err
	}

	m, err := migrate.NewWithInstance(
		"iofs",
		d,
		"sqlite3",
		driver,
	)
	if err != nil {
		return err
	}

	err = m.Up()
	if err != nil && !errors.Is(err, migrate.ErrNoChange) {
		return err
	}

	return nil
}

func MigrateDown(db *sql.DB) error {
	driver, err := sqlite3.WithInstance(db, &sqlite3.Config{})
	if err != nil {
		return err
	}

	d, err := iofs.New(migrations, "migrations")
	if err != nil {
		return err
	}

	m, err := migrate.NewWithInstance(
		"iofs",
		d,
		"sqlite3",
		driver,
	)
	if err != nil {
		return err
	}

	err = m.Down()
	if err != nil && !errors.Is(err, migrate.ErrNoChange) {
		return err
	}

	return nil
}

func OpenSqliteDB(path string, cacheSize int) (*sql.DB, error) {

	if cacheSize == 0 {
		cacheSize = 2000
	}

	err := utils.MkParentDirs(path)
	if err != nil {
		return nil, fmt.Errorf("cannot create parent directories: %w", err)
	}

	dsn := fmt.Sprintf("file:%s?_cache_size=%v&_journal_mode=WAL&_busy_timeout=5000&_foreign_keys=1", path, -cacheSize)

	sqldb, err := sql.Open("sqlite", dsn)
	if err != nil {
		return nil, fmt.Errorf("cannot open sqlite db: %w", err)
	}

	return sqldb, nil
}

func OpenInMemorySqliteDB() (*sql.DB, error) {

	sqldb, err := sql.Open("sqlite", ":memory:")
	if err != nil {
		return nil, fmt.Errorf("cannot open sqlite db: %w", err)
	}

	sqldb.SetMaxOpenConns(1)
	sqldb.SetMaxIdleConns(1)

	return sqldb, nil

}
`

type DBConfig struct {
	PkgName    string
	StructName string
}

func BuildDB(folder string) error {

	config := DBConfig{
		PkgName:    folder,
		StructName: capitalize(folder) + "DB",
	}

	outputPath := filepath.Join(folder, "z_db_gen.go")
	f, _ := os.Create(outputPath)
	fmt.Println("Generated migration file: " + outputPath)
	defer f.Close()

	t := template.Must(template.New("migrations").Parse(dbTmpl))

	err := t.Execute(f, config)
	if err != nil {
		return fmt.Errorf("failed to execute template: %w", err)
	}

	return exec.Command("go", "fmt", outputPath).Run()
}

func capitalize(s string) string {
	if s == "" {
		return s
	}

	return strings.ToUpper(s[:1]) + s[1:]
}
