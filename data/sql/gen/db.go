type DBConfig struct {
	PkgName    string
	StructName string
}

func BuildDB(folder string) error {

	config := DBConfig{
		PkgName:    folder,
		StructName: capitalize(folder) + "DB",
	}

	outputPath := filepath.Join(folder, "z_db_gen.go")
	f, _ := os.Create(outputPath)
	fmt.Println("Generated migration file: " + outputPath)
	defer f.Close()

	t := template.Must(template.New("migrations").Parse(dbTmpl))

	err := t.Execute(f, config)
	if err != nil {
		return fmt.Errorf("failed to execute template: %w", err)
	}

	return exec.Command("go", "fmt", outputPath).Run()
}

func capitalize(s string) string {
	if s == "" {
		return s
	}

	return strings.ToUpper(s[:1]) + s[1:]
}
