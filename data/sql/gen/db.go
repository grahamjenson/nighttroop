func NewDB(ctx context.Context, subdomain *string, cacheSize int, serverConfig *config.ServerConfig) (*DB, error) {
	path, backuppath, s3path, s3archivepath := GetPathsForEverything(subdomain, serverConfig)
	
	db := &DB{
		ServerConfig: serverConfig,
		InMemory:     serverConfig.IsTest(),
		Path:        path,
		BackupPath:  backuppath,
		S3Path:      s3path,
		S3ArchivePath: s3archivepath,
	}

	var err error
	var sqldb *sql.DB

	if serverConfig.IsTest() {
		sqldb, err = OpenInMemorySqliteDB()
	} else {
		sqldb, err = OpenSqliteDB(path, cacheSize)
	}
	if err != nil {
		return nil, fmt.Errorf("{{.PkgName}} db cannot open for: %s %w", path, err)
	}
	db.SQLiteDB = sqldb

	err = MigrateUp(sqldb)
	if err != nil {
		sqldb.Close()
		return db, fmt.Errorf("{{.PkgName}} Migration Error for: %s %w", path, err)
	}

	
	slog.Info("{{.PkgName}} Migration applied successfully to " + path)

	db.Queries, err = Prepare(ctx, sqldb)
	if err != nil {
		sqldb.Close()
		return db, fmt.Errorf("{{.PkgName}} Prepare Error for: %s %w", path, err)
	}
		
	return db, nil
}

func (db *DB) Name() string {
	return "{{.PkgName}}"
}

func (db *DB) MigrateDown() error {
	return MigrateDown(db.SQLiteDB)
}

func (db *DB) GetRawDB() *sql.DB {
	return db.SQLiteDB
}

func (db *DB) Close() error {
	if db == nil || db.SQLiteDB == nil {
		return nil
	}
	return db.SQLiteDB.Close()
}

func (db *DB) TryCloseAndDelete() {
	err := db.Close()
	if err != nil {
		slog.Error("TryCloseAndDelete:Error closing DB: " + err.Error())
		return
	}

	if db.InMemory {
		return
	}
		
	utils.DeleteFile(db.Path)
	utils.DeleteFile(db.BackupPath)
}

func (db *DB) Backup(ctx context.Context) error {
	return backup.SqliteBackup(ctx, db.SQLiteDB, db.BackupPath)
}

