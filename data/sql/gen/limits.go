package gen

import (
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strconv"
	"strings"
)

var (
	createTable = regexp.MustCompile(`(?s)CREATE TABLE (\w+) \((.*?)\n\) STRICT;`)
	sqlNumber   = `(-?\d+(?:\.\d+)?)`
)

// columnLimit is what a column's NOT NULL and CHECK take, as sitedb.ColumnLimit keeps it
type columnLimit struct {
	field, column              string
	required                   bool
	min, max                   *float64
	minExclusive, maxExclusive bool
	minLength, maxLength       int
}

// BuildLimits writes z_limits.go in the folder: each table's columns' limits, from its schema_gen.sql, by the name of
// the column's field in sqlc's rows, so a row can be checked before it is written, and a value the database would
// refuse found by its field
func BuildLimits(folder string) error {
	schema, err := os.ReadFile(filepath.Join(folder, "schema_gen.sql"))
	if err != nil {
		return fmt.Errorf("failed to read the schema: %w", err)
	}
	tables := map[string][]columnLimit{}
	for _, table := range createTable.FindAllStringSubmatch(string(schema), -1) {
		for _, line := range strings.Split(table[2], "\n") {
			if limit, ok := parseColumnLimit(line); ok {
				tables[table[1]] = append(tables[table[1]], limit)
			}
		}
	}

	var out strings.Builder
	fmt.Fprintf(&out, "// Code generated by gensql.go from schema_gen.sql; DO NOT EDIT.\n\npackage %s\n\n", filepath.Base(folder))
	out.WriteString("// columnLimits are each table's columns' limits, by their field's name\n")
	out.WriteString("var columnLimits = map[string]map[string]ColumnLimit{\n")
	names := make([]string, 0, len(tables))
	for name := range tables {
		names = append(names, name)
	}
	slices.Sort(names)
	for _, name := range names {
		fmt.Fprintf(&out, "%q: {\n", name)
		for _, l := range tables[name] {
			fields := []string{fmt.Sprintf("Column: %q", l.column)}
			if l.required {
				fields = append(fields, "Required: true")
			}
			if l.min != nil {
				fields = append(fields, "Min: new("+floatLiteral(*l.min)+")")
			}
			if l.minExclusive {
				fields = append(fields, "MinExclusive: true")
			}
			if l.max != nil {
				fields = append(fields, "Max: new("+floatLiteral(*l.max)+")")
			}
			if l.maxExclusive {
				fields = append(fields, "MaxExclusive: true")
			}
			if l.minLength > 0 {
				fields = append(fields, fmt.Sprintf("MinLength: %d", l.minLength))
			}
			if l.maxLength > 0 {
				fields = append(fields, fmt.Sprintf("MaxLength: %d", l.maxLength))
			}
			fmt.Fprintf(&out, "%q: {%s},\n", l.field, strings.Join(fields, ", "))
		}
		out.WriteString("},\n")
	}
	out.WriteString("}\n")

	src, err := format.Source([]byte(out.String()))
	if err != nil {
		return fmt.Errorf("failed to format the limits: %w", err)
	}
	return os.WriteFile(filepath.Join(folder, "z_limits.go"), src, 0o644)
}

// parseColumnLimit is the limit of the column a line of a CREATE TABLE defines, and false for a line that defines none,
// such as a comment or a table's constraint
func parseColumnLimit(line string) (columnLimit, bool) {
	if i := strings.Index(line, "--"); i >= 0 {
		line = line[:i]
	}
	words := strings.Fields(line)
	if len(words) < 2 || slices.Contains([]string{"UNIQUE", "PRIMARY", "FOREIGN", "CONSTRAINT", "CHECK"}, words[0]) {
		return columnLimit{}, false
	}
	column := words[0]
	limit := columnLimit{field: sqlcFieldName(column), column: column,
		required: strings.Contains(line, "NOT NULL") || strings.Contains(line, "PRIMARY KEY")}
	quoted := regexp.QuoteMeta(column)
	for _, m := range regexp.MustCompile(`\b`+quoted+`\s+BETWEEN\s+`+sqlNumber+`\s+AND\s+`+sqlNumber).FindAllStringSubmatch(line, -1) {
		limit.min, limit.max = parseNumber(m[1]), parseNumber(m[2])
	}
	for _, m := range regexp.MustCompile(`(?:^|[\s(])`+quoted+`\s*(>=|<=|>|<)\s*`+sqlNumber).FindAllStringSubmatch(line, -1) {
		switch m[1] {
		case ">=", ">":
			limit.min, limit.minExclusive = parseNumber(m[2]), m[1] == ">"
		case "<=", "<":
			limit.max, limit.maxExclusive = parseNumber(m[2]), m[1] == "<"
		}
	}
	for _, m := range regexp.MustCompile(`length\(`+quoted+`\)\s*(<=|<|=|>=|>)\s*(\d+)`).FindAllStringSubmatch(line, -1) {
		n, _ := strconv.Atoi(m[2])
		switch m[1] {
		case "<=":
			limit.maxLength = n
		case "<":
			limit.maxLength = n - 1
		case "=":
			limit.minLength, limit.maxLength = n, n
		case ">=":
			limit.minLength = n
		case ">":
			limit.minLength = n + 1
		}
	}
	return limit, true
}

// floatLiteral is a number as a Go float64 constant
func floatLiteral(f float64) string {
	s := strconv.FormatFloat(f, 'f', -1, 64)
	if !strings.Contains(s, ".") {
		s += ".0"
	}
	return s
}

func parseNumber(s string) *float64 {
	f, _ := strconv.ParseFloat(s, 64)
	return &f
}

// sqlcFieldName is the name sqlc gives a column's field: each word of it capitalised, and id as ID
func sqlcFieldName(column string) string {
	words := strings.Split(column, "_")
	for i, word := range words {
		if word == "id" {
			words[i] = "ID"
		} else if word != "" {
			words[i] = strings.ToUpper(word[:1]) + word[1:]
		}
	}
	return strings.Join(words, "")
}
