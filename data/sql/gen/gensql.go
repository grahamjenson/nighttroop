//go:build ignore

package main

import (
	"flag"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"nighttroop.t1d.nz/data/sql/gen"
)

type Config struct {
	Name    string
	Structs []StructInfo
}

type StructInfo struct {
	Name            string
	NameWithoutStmt string
	AttributeName   string
	PkgAndName      string
	NewFunction     string
}

const tmpl = `// Code generated by combine.go; DO NOT EDIT.
package sql

import (
	"fmt"
	"context"
	"database/sql"
	"time"
	_ "embed"
)

type {{.Name}}Statements struct {
	{{range .Structs}}
	{{.AttributeName}} *{{.PkgAndName}}
	{{end}}
}

func New{{.Name}}Statements(sqldb *sql.DB) (*{{.Name}}Statements, error) {

	var errs []error
	stmts := &{{.Name}}Statements{
		{{range .Structs}}
		{{.AttributeName}}: {{.NewFunction}}(sqldb, &errs),
		{{end}}
	}

	if finalErr := errors.Join(errs...); finalErr != nil {
		return nil, finalErr
	}

	return stmts, nil
}
`

func main() {
	folder := flag.String("folder", "", "SQL file to embed")
	limits := flag.Bool("limits", false, "write the columns' limits, z_limits.go")

	flag.Parse()

	if *folder == "" {
		flag.Usage()
		os.Exit(1)
	}

	if fileInfo, err := os.Stat(*folder); err != nil || !fileInfo.IsDir() {
		log.Fatalf("Invalid folder: " + *folder)
	}

	migrationFiles := getMigrationFiles(*folder + "/migrations")

	// This builds the migration file
	err := gen.BuildDB(*folder)
	if err != nil {
		log.Fatalf("Failed to build migration: %v", err)
	}

	err = gen.BuildSchema(*folder+"/schema_gen.sql", migrationFiles)
	if err != nil {
		log.Fatalf("Failed to build schema: %v", err)
	}

	err = gen.BuildSQLC(*folder)
	if err != nil {
		log.Fatalf("Failed to build SQLC: %v", err)
	}

	if *limits {
		if err := gen.BuildLimits(*folder); err != nil {
			log.Fatalf("Failed to build limits: %v", err)
		}
	}

}

func getSQLFilesToParse(folder string) []string {
	var sqlFiles []string

	err := filepath.WalkDir(folder, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}

		if d.IsDir() {
			return nil
		}

		// if the parent folder is called "migrations" then we want to ignore the sql files in there as they are for migrations and not prepared statements
		if strings.HasSuffix(path, ".sql") && !strings.Contains(path, "migrations") {
			sqlFiles = append(sqlFiles, path)
		}

		return nil
	})
	if err != nil {
		panic(err)
	}

	return sqlFiles
}

func getMigrationFiles(folder string) []string {
	var sqlFiles []string

	err := filepath.WalkDir(folder, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}

		if d.IsDir() {
			return nil
		}

		if strings.HasSuffix(path, ".up.sql") && strings.Contains(path, "migrations") {
			sqlFiles = append(sqlFiles, path)
		}

		return nil
	})
	if err != nil {
		panic(err)
	}

	// sort into lexographical order so they run in the order they were added
	sort.Strings(sqlFiles)
	return sqlFiles
}
