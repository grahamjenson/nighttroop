func BuildPrepared(file string) error {

	content, err := os.ReadFile(file)
	if err != nil {
		return fmt.Errorf("failed to read file: %w", err)
	}

	// in the file content there is a line starting with --IN: followed by comma separated list of "Name Type" pairs

	inputs := Inputs{}
	seenIn := false
	for _, line := range strings.Split(string(content), "\n") {
		line = strings.TrimSpace(line)
		if !strings.HasPrefix(line, "--IN:") {
			continue
		}
		if seenIn {
			return fmt.Errorf("multiple --IN: lines found in file %s", file)
		}
		seenIn = true
		inputstr := strings.TrimPrefix(line, "--IN:")
		if inputstr == "" {
			continue
		}
		for _, input := range strings.Split(inputstr, ",") {
			input = strings.TrimSpace(input)
			if input == "" {
				continue
			}
			parts := strings.Fields(input)
			if len(parts) != 2 {
				return fmt.Errorf("Invalid input format: %s", input)
			}
			inputs = append(inputs, Input{
				Name: sanitizeName(parts[0]),
				Type: parts[1],
			})

		}
	}

	if !seenIn {
		return fmt.Errorf("no --IN: line found in file %s", file)
	}

	var modelOutputs Outputs = []Output{}
	seenOut := false
	for _, line := range strings.Split(string(content), "\n") {
		line = strings.TrimSpace(line)
		if !strings.HasPrefix(line, "--OUT:") {
			continue
		}
		if seenOut {
			return fmt.Errorf("multiple --OUT: lines found in file %s", file)
		}
		seenOut = true
		outputs := strings.TrimPrefix(line, "--OUT:")
		if outputs == "" {
			continue
		}
		for _, output := range strings.Split(outputs, ",") {
			output = strings.TrimSpace(output)
			if output != "" {
				parts := strings.Fields(output)
				if len(parts) != 2 {
					return fmt.Errorf("Invalid output format: %s", output)
				}
				modelOutputs = append(modelOutputs, Output{
					Name:            sanitizeName(parts[0]),
					Type:            parts[1],
					CapitalizedName: utils.SnakeToCapitalCamelCase(parts[0]),
				})
			}
		}
	}

	if !seenOut {
		return fmt.Errorf("no --OUT: line found in file %s", file)
	}

	inputsCount := len(inputs)
	outputsCount := len(modelOutputs)

	////
	// Check SQL against parser for correctness
	////
	sqlstats := ParseSQL(string(content)) // Just to validate the SQL and error if it's not valid
	switch sqlstats.Type {
	case "SELECT":
		if sqlstats.Parameters != inputsCount {
			return fmt.Errorf("%s : Expected %d input parameters based on SQL, but got %d", file, sqlstats.Parameters, inputsCount)

		}
		if sqlstats.Columns != outputsCount {
			return fmt.Errorf("%s : Expected %d output columns based on SQL, but got %d", file, sqlstats.Columns, outputsCount)
		}
	case "INSERT", "DELETE", "UPDATE":
		if sqlstats.Parameters != inputsCount {
			return fmt.Errorf("%s : Expected %d input parameters based on SQL, but got %d", file, sqlstats.Parameters, inputsCount)
		}
		if outputsCount != 0 {
			return fmt.Errorf("%s : Expected 0 output columns for %s statement, but got %d", file, sqlstats.Type, outputsCount)
		}
	default:
		return fmt.Errorf("%s : Unsupported SQL statement type: %s", file, sqlstats.Type)
	}

	// file is like user/devices_get.sql
	inputFileName := filepath.Base(file) // devices_get.sql
	inputFileDir := filepath.Dir(file)
	pkg := filepath.Base(inputFileDir)

	outfilename := strings.TrimSuffix(inputFileName, ".sql")
	name := utils.SnakeToCapitalCamelCase(outfilename)

	interfaceName := "I" + name
	if interfaceName == "IGet" {
		interfaceName = "I" + utils.SnakeToCapitalCamelCase(pkg)
	}

	cfg := PreparedConfig{
		Name:          name,
		Package:       pkg,
		Content:       string(content),
		Inputs:        inputs,
		Outputs:       modelOutputs,
		InterfaceName: interfaceName,
	}

	outputPath := filepath.Join(inputFileDir, "/z_"+outfilename+"_gen.go")
	t := template.Must(template.New("sql").Parse(preparedTmpl))
	f, err := os.Create(outputPath)
	if err != nil {
		return fmt.Errorf("failed to create output file: %w", err)
	}
	defer f.Close()

	err = t.Execute(f, cfg)
	if err != nil {
		return fmt.Errorf("failed to execute template: %w", err)

	}

	// Format the generated code
	return exec.Command("go", "tool", "goimports", "-w", outputPath).Run()
}

