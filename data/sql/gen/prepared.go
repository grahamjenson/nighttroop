type PreparedConfig struct {
	Name    string
	Package string
	Content string

	Inputs        Inputs
	Outputs       Outputs
	InterfaceName string
}

type Output struct {
	Name            string
	CapitalizedName string
	Type            string
}

func (o Output) PublicName() string {
	return strings.ToUpper(string(o.Name[0])) + o.Name[1:]
}

type Outputs []Output

func (o Outputs) OutputsVariableList() string {
	res := []string{}
	for _, output := range o {

		res = append(res, "model."+output.Name)

	}
	return strings.Join(res, ", ")
}

func (o Outputs) OutputsModelList() string {
	res := []string{}
	for _, output := range o {

		res = append(res, "&model."+output.Name)

	}
	return strings.Join(res, ", ")
}

func (o Outputs) OutputsTypesList() string {
	res := []string{}
	for _, output := range o {
		res = append(res, output.Type)
	}
	return strings.Join(res, ", ")
}

type Input struct {
	Name string
	Type string
}

type Inputs []Input

func (i Inputs) InputParamsList() string {
	res := []string{}
	for _, input := range i {
		res = append(res, input.Name)
	}
	return strings.Join(res, ", ")
}

func (i Inputs) InputsList() string {
	res := []string{}
	for _, input := range i {
		res = append(res, input.Name+" "+input.Type)
	}
	return strings.Join(res, ", ")
}

