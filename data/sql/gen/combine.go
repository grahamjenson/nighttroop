//go:build ignore

package main

import (
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"text/template"

	"nighttroop.t1d.nz/utils"
)

type Config struct {
	Name    string
	Structs []StructInfo
}

type StructInfo struct {
	Name            string
	NameWithoutStmt string
	AttributeName   string
	PkgAndName      string
	NewFunction     string
}

const tmpl = `// Code generated by combine.go; DO NOT EDIT.
package sql

import (
	"fmt"
	"context"
	"database/sql"
	"time"
	_ "embed"
)

type {{.Name}}Statements struct {
	{{range .Structs}}
	{{.AttributeName}} *{{.PkgAndName}}
	{{end}}
}

func New{{.Name}}Statements(sqldb *sql.DB) (*{{.Name}}Statements, error) {

	var errs []error
	stmts := &{{.Name}}Statements{
		{{range .Structs}}
		{{.AttributeName}}: {{.NewFunction}}(sqldb, &errs),
		{{end}}
	}

	if finalErr := errors.Join(errs...); finalErr != nil {
		return nil, finalErr
	}

	return stmts, nil
}
`

func main() {
	folder := flag.String("folder", "", "SQL file to embed")

	flag.Parse()

	if *folder == "" {
		flag.Usage()
		os.Exit(1)
	}

	if fileInfo, err := os.Stat(*folder); err != nil || !fileInfo.IsDir() {
		panic("Invalid folder: " + *folder)
	}

	var goFiles []string

	err := filepath.WalkDir(*folder, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}

		if d.IsDir() {
			return nil
		}

		if strings.HasSuffix(path, "_gen.go") {
			goFiles = append(goFiles, path)
		}

		return nil
	})
	if err != nil {
		panic(err)
	}

	structs := []StructInfo{}

	for _, file := range goFiles {
		fmt.Println("Parsing file: " + file)
		_, fileStructs, err := GetStmtsFromFile(file)
		if err != nil {
			panic(fmt.Sprintf("Failed to parse structs from file %s: %v", file, err))
		}
		structs = append(structs, fileStructs...)

	}

	// Build the config
	cfg := Config{
		Name:    utils.SnakeToCapitalCamelCase(*folder),
		Structs: structs,
	}

	outputPath := filepath.Join("./z_" + *folder + "_gen.go")
	t := template.Must(template.New("sql").Parse(tmpl))
	f, _ := os.Create(outputPath)
	defer f.Close()

	err = t.Execute(f, cfg)
	if err != nil {
		panic(fmt.Sprintf("Failed to execute template: %v", err))
	}

	// Format the generated code
	exec.Command("go", "tool", "goimports", "-w", outputPath).Run()
}

func exprToString(expr ast.Expr) string {
	switch t := expr.(type) {
	case *ast.Ident:
		return t.Name
	case *ast.SelectorExpr:
		return exprToString(t.X) + "." + t.Sel.Name
	case *ast.StarExpr:
		return "*" + exprToString(t.X)
	case *ast.ArrayType:
		return "[]" + exprToString(t.Elt)
	default:
		return fmt.Sprintf("%T", expr) // fallback
	}
}

func GetStmtsFromFile(filePath string) (string, []StructInfo, error) {
	fset := token.NewFileSet()

	node, err := parser.ParseFile(fset, filePath, nil, parser.SkipObjectResolution)
	if err != nil {
		return "", nil, fmt.Errorf("parse error in %s: %w", filePath, err)
	}

	pkgName := node.Name.Name
	pkgNameCapital := strings.Title(pkgName)
	var structs []StructInfo

	ast.Inspect(node, func(n ast.Node) bool {
		ts, ok := n.(*ast.TypeSpec)
		if !ok {
			return true
		}

		name := ts.Name.Name
		if strings.HasSuffix(name, "Stmt") {
			nameWithoutStmt := strings.TrimSuffix(name, "Stmt")
			attributeName := pkgNameCapital + nameWithoutStmt
			s := StructInfo{
				Name:            name,
				NameWithoutStmt: nameWithoutStmt,
				AttributeName:   attributeName,
				PkgAndName:      fmt.Sprintf("%s.%s", pkgName, name),
				NewFunction:     fmt.Sprintf("%s.New%s", pkgName, nameWithoutStmt),
			}

			structs = append(structs, s)
		}
		return false
	})

	return pkgName, structs, nil
}
