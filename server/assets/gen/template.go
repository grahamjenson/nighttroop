//go:build ignore

package main

import (
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"text/template"

	"nighttroop.t1d.nz/utils"
)

const tmpl = `// Code generated by prepared.go; DO NOT EDIT.
package {{.Package}}

import (
	"fmt"
	"io"
	_ "embed"
	"text/template"
{{- range .AdditionalPackages}}
	"{{.}}"
{{- end}}
)

//go:embed {{.TemplateBase}}
var {{.Name}}Base string

{{- range .GetFileVars}}

//go:embed {{.FileName}}
var {{.VarName}} string

{{- end}}


var {{.Name}}Template *template.Template


func get{{.Name}}Template() (*template.Template, error) {
	if {{.Name}}Template != nil {
		return {{.Name}}Template, nil
	}

	{{.Name}}Template, err := template.New("{{.Name}}").Parse({{ .Name }}Base )
	if err != nil {
		return nil, err
	}
	
	{{- if .HasFiles}}
	{{.Name}}Template, err = {{.Name}}Template.Parse({{ .JoinFileVarsWithPlus }})
	if err != nil {
		return nil, err
	}
	{{- end}}


	return {{.Name}}Template, nil
}

func {{.Name}}(w io.Writer{{ if .HasInputs }}, {{.Inputs}} {{ end }}) error {
	tmpl, err := get{{.Name}}Template()
	if err != nil {
		return fmt.Errorf("failed to get template: %w", err)
	}

	{{ if .HasInputs }}
		err = tmpl.Execute(w, map[string]any{ {{.InputParams}} })
	{{ else }}
		err = tmpl.Execute(w, nil)
	{{ end }}
	if err != nil {
		return fmt.Errorf("failed to execute template: %w", err)
	}
	return nil
}

`

type Config struct {
	Name               string
	Package            string
	TemplateBase       string
	TemplateFiles      utils.FlagFileList
	HasInputs          bool
	Inputs             string
	InputParams        string
	AdditionalPackages []string
	HasFiles           bool
}

func (c Config) GetFileVars() []utils.FlagStringFileName {

	ll := []utils.FlagStringFileName{}
	for _, l := range c.TemplateFiles.GetFileVars() {
		ll = append(ll, utils.FlagStringFileName{
			FileName: utils.RelPathBetween(c.Package, l.FileName),
			VarName:  c.Name + l.VarName,
		})
	}
	return ll
}

func (c Config) JoinFileVarsWithPlus() string {
	var quoted []string
	for _, file := range c.GetFileVars() {
		quoted = append(quoted, file.VarName)
	}

	return strings.Join(quoted, " + ")
}

func main() {
	var templateFiles utils.FlagFileList

	base := flag.String("base", "", "BaseTemplate")
	flag.Var(&templateFiles, "file", "Template files to embed")

	inputs := flag.String("in", "", "Comma-separated inputs (e.g. 'ID int,Name string')")
	flag.Parse()

	if base == nil || *base == "" {
		panic("Base template is required")
	}

	for _, file := range templateFiles {
		if fileInfo, err := os.Stat("templates/" + file); err != nil || fileInfo.IsDir() {
			panic("Invalid file: " + file)
		}
	}

	filePathToUse := *base
	if len(templateFiles) > 0 {
		filePathToUse = templateFiles[0]
	}
	filenameToUse := filepath.Base(filePathToUse)
	outfilename := strings.TrimSuffix(filenameToUse, filepath.Ext(filenameToUse))
	name := utils.SnakeToCapitalCamelCase(outfilename)
	pkg := filepath.Dir(filePathToUse)

	additionalPackages := []string{}
	if strings.Contains(*inputs, "time.Time") {
		// If any input or output includes time.Time, we need to import the time package
		additionalPackages = append(additionalPackages, "time")
	}

	// inputParams is a string params.{name}, params.{name}, ...
	inputParms := []string{}
	for _, param := range strings.Split(*inputs, ",") {
		param = strings.TrimSpace(param)
		if param != "" {
			parts := strings.Fields(param)
			if len(parts) == 2 {

				inputParms = append(inputParms, fmt.Sprintf(`"%s": %s`, parts[0], parts[0]))
			} else {
				panic("Invalid input parameter format: " + param)
			}
		}
	}

	inputList := []string{}
	for _, input := range strings.Split(*inputs, ",") {
		cleanI := strings.TrimSpace(input)
		if cleanI == "" {
			continue
		}
		inputList = append(inputList, cleanI)
	}

	cfg := Config{
		Name:               name,
		Package:            pkg,
		TemplateBase:       utils.RelPathBetween(pkg, *base),
		TemplateFiles:      templateFiles,
		HasFiles:           len(templateFiles) != 0,
		Inputs:             *inputs,
		InputParams:        strings.Join(inputParms, ", "),
		HasInputs:          len(inputList) != 0,
		AdditionalPackages: additionalPackages,
	}

	outputPath := "templates/" + pkg + "/z_" + outfilename + "_gen.go"
	t := template.Must(template.New(name + "Template").Parse(tmpl))
	f, _ := os.Create(outputPath)
	defer f.Close()

	err := t.Execute(f, cfg)
	if err != nil {
		panic(fmt.Sprintf("Failed to execute template: %v", err))
	}
	// Format the generated code
	exec.Command("go", "fmt", outputPath).Run()
}
