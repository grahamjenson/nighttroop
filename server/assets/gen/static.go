const tmpl = `// Code generated by prepared.go; DO NOT EDIT.
package static

import (
	"bytes"
	"compress/gzip"
	"fmt"
	"net/http"
	"log/slog"
	"crypto/sha256"
	"encoding/hex"
	"strings"
	"sync"
	_ "embed"
	
	"github.com/go-chi/chi/v5"

)

{{- range .GetFileVars}}

//go:embed {{.FileName}}
var {{.VarName}} []byte
var {{.VarName}}ETag = generateETag([]byte({{.VarName}}))
{{- if .Gzip}}
var {{.VarName}}Gzip = sync.OnceValue(func() []byte { return gzipped({{.VarName}}) })
{{- end}}

{{- end}}


func AddStaticRoutes(r chi.Router) error {
	{{- range .GetFileVars }}
	r.Get("/{{.FileName}}", func(w http.ResponseWriter, r *http.Request) {
		serve(w, r, "{{.FileName}}", "{{.ContentType}}", {{.VarName}}ETag, {{.VarName}}, {{if .Gzip}}{{.VarName}}Gzip{{else}}nil{{end}})
	})
	{{- end}}

	return nil
}

// serve writes a file, gzipped once and kept for clients that accept it, so a request does not compress it again
func serve(w http.ResponseWriter, r *http.Request, fileName string, contentType string, etag string, body []byte, gzipBody func() []byte) {
	w.Header().Set("Content-Type", contentType)

	// URLs are not versioned, so browsers must revalidate with the ETag to see new deploys
	w.Header().Set("Cache-Control", "no-cache")
	w.Header().Set("ETag", etag)
	if gzipBody != nil {
		w.Header().Add("Vary", "Accept-Encoding")
	}
	if r.Header.Get("If-None-Match") == etag {
		w.WriteHeader(http.StatusNotModified)
		return
	}

	if gzipBody != nil && strings.Contains(r.Header.Get("Accept-Encoding"), "gzip") {
		// The compress middleware leaves a response that already has an encoding
		w.Header().Set("Content-Encoding", "gzip")
		body = gzipBody()
	}

	_, err := w.Write(body)
	if err != nil {
		slog.Error("Failed to write response for " + fileName, "error", err)
	}
}

func gzipped(body []byte) []byte {
	var buf bytes.Buffer
	writer, _ := gzip.NewWriterLevel(&buf, gzip.BestCompression)
	writer.Write(body)
	writer.Close()
	return buf.Bytes()
}

func generateETag(data []byte) string {
	hash := sha256.Sum256(data)
	// Return the first 16 chars of the hash wrapped in double quotes
	return fmt.Sprintf("\"%s\"", hex.EncodeToString(hash[:8]))
}
`

type Config struct {
	StaticFiles utils.FlagFileList
}

type StaticFile struct {
	FileName    string
	VarName     string
	ContentType string
	// Gzip is for text, which compresses well; images like PNGs are already compressed
	Gzip bool
}

func (c Config) GetFileVars() []StaticFile {

	ll := []StaticFile{}
	for _, l := range c.StaticFiles.GetFileVars() {
		ll = append(ll, StaticFile{
			FileName:    l.FileName,
			VarName:     "Static" + l.VarName,
			ContentType: getContentType(l.FileName),
			Gzip:        gzipTypes[filepath.Ext(l.FileName)],
		})
	}
	return ll
}

// contentTypes is a fixed table so generated output does not depend on the
// host OS mime database (which differs between macOS and Linux).
var contentTypes = map[string]string{
	".css":   "text/css; charset=utf-8",
	".js":    "text/javascript; charset=utf-8",
	".mjs":   "text/javascript; charset=utf-8",
	".json":  "application/json",
	".txt":   "text/plain; charset=utf-8",
	".html":  "text/html; charset=utf-8",
	".svg":   "image/svg+xml",
	".png":   "image/png",
	".jpg":   "image/jpeg",
	".jpeg":  "image/jpeg",
	".gif":   "image/gif",
	".webp":  "image/webp",
	".ico":   "image/x-icon",
	".woff":  "font/woff",
	".woff2": "font/woff2",
	".wasm":  "application/wasm",
}

var gzipTypes = map[string]bool{".css": true, ".js": true, ".mjs": true, ".json": true, ".txt": true, ".html": true, ".svg": true}

func getContentType(filename string) string {
	if contentType, ok := contentTypes[filepath.Ext(filename)]; ok {
		return contentType
	}
	return "application/octet-stream" // Default for generic binary data
}

func main() {
	var staticFiles utils.FlagFileList

	// loop over the folder ../static and add all files to the StaticFiles list
	err := filepath.Walk("static", func(path string, info os.FileInfo, err error) error {

		if err != nil {
			return err
		}
		// Not the Go files here, like this generated one, which are code rather than files to serve
		if !info.IsDir() && filepath.Ext(path) != ".go" {
			relativePath, err := filepath.Rel("static", path)
			if err != nil {
				return err
			}
			staticFiles = append(staticFiles, relativePath)
		}
		return nil
	})
	if err != nil {
		panic(fmt.Sprintf("Failed to walk static directory: %v", err))
	}

	for _, file := range staticFiles {
		if fileInfo, err := os.Stat("static/" + file); err != nil || fileInfo.IsDir() {
			panic("Invalid file: " + file)
		}
	}

	cfg := Config{
		StaticFiles: staticFiles,
	}

	outputPath := "static/z_static_gen.go"
	t := template.Must(template.New("StaticTemplate").Parse(tmpl))
	f, _ := os.Create(outputPath)
	defer f.Close()

	err = t.Execute(f, cfg)
	if err != nil {
		panic(fmt.Sprintf("Failed to execute template: %v", err))
	}
	// Format the generated code
	exec.Command("go", "fmt", outputPath).Run()
}
