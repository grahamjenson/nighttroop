// docs renders the terms of service and privacy policy from their Markdown into HTML, in docs/docs.gen.go, so the
// server serves them without parsing Markdown. Run from server/assets.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"

	"github.com/yuin/goldmark"
)

func main() {
	var out bytes.Buffer
	out.WriteString("// Code generated by gen/docs; DO NOT EDIT.\n\npackage docs\n\n")
	for _, doc := range []struct{ name, file string }{
		{"TermsOfService", "TERMS_OF_SERVICE.md"},
		{"PrivacyPolicy", "PRIVACY_POLICY.md"},
	} {
		markdown, err := os.ReadFile(filepath.Join("docs", doc.file))
		if err != nil {
			log.Fatal(err)
		}
		var html bytes.Buffer
		if err := goldmark.Convert(markdown, &html); err != nil {
			log.Fatal(err)
		}
		fmt.Fprintf(&out, "// %s is %s as HTML\nconst %s = %q\n\n", doc.name, doc.file, doc.name, html.String())
	}
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join("docs", "docs.gen.go"), formatted, 0o644); err != nil {
		log.Fatal(err)
	}
}
