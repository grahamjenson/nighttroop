type Config struct {
	FolderName   string
	BaseFile     string
	Templates    TemplateDataList
	HTMXTemplate string
}

type TemplateData struct {
	Name     string
	FileName string

	AllInputs      string
	AllInputParams string

	HasAllInputs bool
}

type TemplateDataList []TemplateData

func main() {
	folder := flag.String("folder", "", "Folder Name")
	flag.Parse()

	baseFilePath := *folder + "/base.html"
	if _, err := os.Stat(baseFilePath); os.IsNotExist(err) {
		panic("Base template is required: " + baseFilePath)
	}

	baseFileInputs, baseFileInputParams := extractInputsFromTemplateFile(baseFilePath)
	templateFiles := getAllTemplateFiles(*folder)
	templateDataList := buildTemplateDataList(*folder, templateFiles, baseFileInputs, baseFileInputParams)
	cfg := Config{
		FolderName:   utils.SnakeToCapitalCamelCase(*folder),
		BaseFile:     baseFilePath,
		Templates:    templateDataList,
		HTMXTemplate: "`{{ block \"content\" . }}{{ end }}`",
	}

	outputPath := "./z_" + *folder + "_gen.go"
	t := template.Must(template.New(*folder + "Template").Parse(tmpl))
	f, _ := os.Create(outputPath)
	defer f.Close()

	err := t.Execute(f, cfg)
	if err != nil {
		panic(fmt.Sprintf("Failed to execute template: %v", err))
	}

	// Format the generated code
	exec.Command("go", "tool", "goimports", "-w", outputPath).Run()
}

// Get All Files
// walk throught the template/folder dir and grab all .html files expect base.html
func getAllTemplateFiles(folder string) []string {
	files := []string{}

	err := filepath.Walk(folder, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		if !info.IsDir() && filepath.Ext(path) == ".html" && filepath.Base(path) != "base.html" {
			files = append(files, path)
		}
		return nil
	})
	if err != nil {
		panic(fmt.Sprintf("Failed to walk through folder: %v", err))
	}
	return files
}

func buildTemplateDataList(folder string, files []string, baseFileInputs, baseFileInputParams []string) TemplateDataList {
	templateList := TemplateDataList{}

	for _, file := range files {

		name := strings.TrimSuffix(file, ".html")
		name = strings.ReplaceAll(name, "/", "_")
		name = utils.SnakeToCapitalCamelCase(name)
		inputs, inputParams := extractInputsFromTemplateFile(file)
		allInputs := []string{}
		allInputParams := []string{}

		// Combine base file inputs with template specific inputs
		allInputs = append(allInputs, baseFileInputs...)
		allInputs = append(allInputs, inputs...)

		allInputParams = append(allInputParams, baseFileInputParams...)
		allInputParams = append(allInputParams, inputParams...)

		templateList = append(templateList, TemplateData{
			Name:     name,
			FileName: file,

			AllInputs:      strings.Join(allInputs, ", "),
			AllInputParams: strings.Join(allInputParams, ", "),

			HasAllInputs: len(allInputs) > 0,
		})
	}
	return templateList
}

func extractInputsFromTemplateFile(filePath string) ([]string, []string) {
	// In the file there is are many comments like {{/*PARAM ... */}} we want to extract and combine
	content, err := os.ReadFile(filePath)
	if err != nil {
		panic(fmt.Sprintf("Failed to read template file: %v", err))
	}
	strContent := string(content)
	lines := strings.Split(strContent, "\n")
	inputs := []string{}
	inputParams := []string{}

	for _, line := range lines {
		line = strings.TrimSpace(line)
		if strings.HasPrefix(line, "{{/*PARAM") && strings.HasSuffix(line, "*/}}") {
			paramLine := strings.TrimSuffix(strings.TrimPrefix(line, "{{/*PARAM"), "*/}}")
			paramLine = strings.TrimSpace(paramLine)
			for _, param := range strings.Split(paramLine, ",") {
				param = strings.TrimSpace(param)
				parts := strings.SplitN(param, " ", 2)
				if len(parts) == 2 {
					inputs = append(inputs, parts[0]+" "+parts[1])
					inputParams = append(inputParams, fmt.Sprintf(`"%s": %s`, parts[0], parts[0]))
				}
			}
		}
	}
	return inputs, inputParams

}
