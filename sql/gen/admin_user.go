package main

import (
	"flag"
	"fmt"

	"github.com/pquerna/otp/totp"
	"golang.org/x/crypto/bcrypt"
)

const tmpl = `// Code generated by migration.go; DO NOT EDIT.
package migrations

import (
	"context"
	"database/sql"
	"fmt"
)


`

func main() {
	// TODO: store run migrations so they dont run again and again
	var password string
	var hostname string
	var keyName string
	flag.StringVar(&password, "password", "", "Password for the admin user")
	flag.StringVar(&hostname, "hostname", "nighttroop.t1d.nz", "Hostname for the server (used for TOTP)")
	flag.StringVar(&keyName, "keyname", "", "Name for the encryption key must be 6 bytes long")

	flag.Parse()

	if password == "" {
		panic("Password is required")
	}

	if keyName == "" {
		panic("Key name is required")
	}

	if len([]byte(keyName)) != 6 {
		panic("Key name must be 6 bytes long")
	}

	hashedBytes, err := bcrypt.GenerateFromPassword([]byte(password), bcrypt.DefaultCost)
	if err != nil {
		panic(fmt.Sprintf("Error hashing password: %v", err))
	}

	totpKey, _ := totp.Generate(totp.GenerateOpts{
		Issuer:      "NightTroop",
		AccountName: fmt.Sprintf("admin@%s", hostname),
	})

	totpSecret := totpKey.Secret()

	fmt.Println("Generated Encryption Key", totpSecret, hashedBytes)

}
