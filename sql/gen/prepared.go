//go:build ignore

package main

import (
	"flag"
	"fmt"
	"os"
	"os/exec"
	"strings"
	"text/template"

	"nighttroop.t1d.nz/utils"
)

type Config struct {
	Name               string
	Package            string
	SQLFile            string
	Inputs             string
	Outputs            []string
	InputParams        string
	OutputModel        string
	AdditionalPackages []string
}

const tmpl = `// Code generated by prepared.go; DO NOT EDIT.
package {{.Package}}

import (
	"fmt"
	"context"
	"database/sql"
	_ "embed"
{{- range .AdditionalPackages}}
	"{{.}}"
{{- end}}
)

//go:embed {{.SQLFile}}
var {{.Name}}Raw string

type {{.Name}}Model struct {
{{- range .Outputs}}
	{{.}}
{{- end}}
}

type {{.Name}}Stmt struct {
	stmt  *sql.Stmt
}

// Non standard error collection, but makes it much cleaner on creation since we call so many of these
func New{{.Name}}(sqldb *sql.DB, errs *[]error) *{{.Name}}Stmt {
	var err error
	stmt, err := sqldb.Prepare({{.Name}}Raw)
	if err != nil {
		*errs = append(*errs, fmt.Errorf("{{.Name}} create error: %w", err))
		return nil
	}
	return &{{.Name}}Stmt{stmt: stmt}
}

func (s *{{.Name}}Stmt) Query(ctx context.Context {{if .InputParams}}, {{.Inputs}} {{end}}) ([]{{.Name}}Model, error) {
	rows, err := s.stmt.QueryContext(ctx {{if .InputParams}}, {{.InputParams}}{{end}})
	if err != nil {
		return nil, err
	}
	defer rows.Close()

	var results []{{.Name}}Model
	for rows.Next() {
		var model {{.Name}}Model
		// Scanning into exported fields
		if err := rows.Scan({{.OutputModel}}); err != nil {
			return nil, err
		}
		results = append(results, model)
	}
	return results, nil
}

func (s *{{.Name}}Stmt) Exec(ctx context.Context {{if .InputParams}}, {{.Inputs}}{{end}}) (sql.Result, error) {
	return s.stmt.ExecContext(ctx, {{.InputParams}})
}

func (s *{{.Name}}Stmt) QueryRow(ctx context.Context {{if .InputParams}}, {{.Inputs}}{{end}}) ({{.Name}}Model, error) {
	var model {{.Name}}Model
	err := s.stmt.QueryRowContext(ctx{{if .InputParams}}, {{.InputParams}}{{end}}).Scan({{.OutputModel}})
	if (err != nil) {
		return model, err
	} 
	return model, nil
}
`

func main() {
	file := flag.String("file", "", "SQL file to embed")
	inputs := flag.String("in", "", "Comma-separated inputs (e.g. 'ID int,Name string')")
	outputs := flag.String("out", "", "Comma-separated outputs")
	flag.Parse()

	if *file == "" {
		flag.Usage()
		os.Exit(1)
	}

	if fileInfo, err := os.Stat(*file); err != nil || fileInfo.IsDir() {
		panic("Invalid file: " + *file)
	}

	additionalPackages := []string{}
	if strings.Contains(*inputs, "time.Time") || strings.Contains(*outputs, "time.Time") {
		// If any input or output includes time.Time, we need to import the time package
		additionalPackages = append(additionalPackages, "time")
	}

	// file is like user/devices_get.sql
	parts := strings.Split(*file, "/")
	name := parts[len(parts)-1]
	outfilename := strings.TrimSuffix(name, ".sql")
	name = utils.SnakeToCapitalCamelCase(outfilename)
	sqlfile := parts[len(parts)-1]

	pkg := parts[0]
	// inputParams is a string params.{name}, params.{name}, ...
	inputParms := []string{}
	for _, param := range strings.Split(*inputs, ",") {
		param = strings.TrimSpace(param)
		if param != "" {
			parts := strings.Fields(param)
			if len(parts) == 2 {
				inputParms = append(inputParms, parts[0])
			} else {
				panic("Invalid input parameter format: " + param)
			}
		}
	}

	outputModel := []string{}
	for _, param := range strings.Split(*outputs, ",") {
		param = strings.TrimSpace(param)
		if param != "" {
			parts := strings.Fields(param)
			if len(parts) == 2 {
				outputModel = append(outputModel, "&model."+parts[0])
			}
		}
	}

	cfg := Config{
		Name:               name,
		Package:            pkg,
		SQLFile:            sqlfile,
		Inputs:             *inputs,
		Outputs:            strings.Split(*outputs, ","),
		InputParams:        strings.Join(inputParms, ", "),
		OutputModel:        strings.Join(outputModel, ", "),
		AdditionalPackages: additionalPackages,
	}

	outputPath := pkg + "/z_" + outfilename + "_gen.go"
	t := template.Must(template.New("sql").Parse(tmpl))
	f, _ := os.Create(outputPath)
	defer f.Close()

	err := t.Execute(f, cfg)
	if err != nil {
		panic(fmt.Sprintf("Failed to execute template: %v", err))
	}

	// Format the generated code
	exec.Command("go", "fmt", outputPath).Run()
}
