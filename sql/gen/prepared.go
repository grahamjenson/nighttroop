//go:build ignore

package main

import (
	"flag"
	"os"
	"strings"
	"text/template"
	"unicode"
)

type Config struct {
	Name               string
	Package            string
	SQLFile            string
	Inputs             []string
	Outputs            []string
	InputParams        string
	OutputModel        string
	AdditionalPackages []string
}

const tmpl = `// Code generated by prepared.go; DO NOT EDIT.
package {{.Package}}

import (
	"context"
	"database/sql"
	_ "embed"
{{- range .AdditionalPackages}}
	"{{.}}"
{{- end}}
)

//go:embed {{.SQLFile}}
var {{.Name}}Raw string

type {{.Name}}Params struct {
{{- range .Inputs}}
	{{.}}
{{- end}}
}

type {{.Name}}Model struct {
{{- range .Outputs}}
	{{.}}
{{- end}}
}

type {{.Name}}SQL struct {
	stmt  *sql.Stmt
}

func New{{.Name}}(sqldb *sql.DB) (*{{.Name}}SQL, error) {
	var err error
	stmt, err := sqldb.Prepare({{.Name}}Raw)
	if err != nil {
		return nil, err
	}
	return &{{.Name}}SQL{stmt: stmt}, nil
}

func (s *{{.Name}}SQL) Query(ctx context.Context {{if .InputParams}}, params {{.Name}}Params{{end}}) ([]{{.Name}}Model, error) {
	rows, err := s.stmt.QueryContext(ctx {{if .InputParams}}, {{.InputParams}}{{end}})
	if err != nil {
		return nil, err
	}
	defer rows.Close()

	var results []{{.Name}}Model
	for rows.Next() {
		var model {{.Name}}Model
		// Scanning into exported fields
		if err := rows.Scan({{.OutputModel}}); err != nil {
			return nil, err
		}
		results = append(results, model)
	}
	return results, nil
}

func (s *{{.Name}}SQL) Exec(ctx context.Context, params {{.Name}}Params) (sql.Result, error) {
	return s.stmt.ExecContext(ctx, {{.InputParams}})
}

func (s *{{.Name}}SQL) QueryRow(ctx context.Context {{if .InputParams}}, params {{.Name}}Params{{end}}) {{.Name}}Model {
	var model {{.Name}}Model
	s.stmt.QueryRowContext(ctx{{if .InputParams}}, {{.InputParams}}{{end}}).Scan({{.OutputModel}})
	return model
}
`

func main() {
	file := flag.String("file", "", "SQL file to embed")
	inputs := flag.String("in", "", "Comma-separated inputs (e.g. 'ID int,Name string')")
	outputs := flag.String("out", "", "Comma-separated outputs")
	flag.Parse()

	if *file == "" {
		flag.Usage()
		os.Exit(1)
	}

	if fileInfo, err := os.Stat(*file); err != nil || fileInfo.IsDir() {
		panic("Invalid file: " + *file)
	}

	additionalPackages := []string{}
	if strings.Contains(*inputs, "time.Time") || strings.Contains(*outputs, "time.Time") {
		// If any input or output includes time.Time, we need to import the time package
		additionalPackages = append(additionalPackages, "time")
	}

	// file is like user/devices_get.sql
	parts := strings.Split(*file, "/")
	name := parts[len(parts)-1]
	outfilename := strings.TrimSuffix(name, ".sql")
	name = SnakeToCapitalCamelCase(outfilename)
	sqlfile := parts[len(parts)-1]

	pkg := parts[0]
	// inputParams is a string params.{name}, params.{name}, ...
	inputParms := []string{}
	for _, param := range strings.Split(*inputs, ",") {
		param = strings.TrimSpace(param)
		if param != "" {
			parts := strings.Fields(param)
			if len(parts) == 2 {
				inputParms = append(inputParms, "params."+parts[0])
			} else {
				panic("Invalid input parameter format: " + param)
			}
		}
	}

	outputModel := []string{}
	for _, param := range strings.Split(*outputs, ",") {
		param = strings.TrimSpace(param)
		if param != "" {
			parts := strings.Fields(param)
			if len(parts) == 2 {
				outputModel = append(outputModel, "&model."+parts[0])
			}
		}
	}

	cfg := Config{
		Name:               name,
		Package:            pkg,
		SQLFile:            sqlfile,
		Inputs:             strings.Split(*inputs, ","),
		Outputs:            strings.Split(*outputs, ","),
		InputParams:        strings.Join(inputParms, ", "),
		OutputModel:        strings.Join(outputModel, ", "),
		AdditionalPackages: additionalPackages,
	}

	t := template.Must(template.New("sql").Parse(tmpl))
	f, _ := os.Create(pkg + "/z_" + outfilename + "_gen.go")
	defer f.Close()
	t.Execute(f, cfg)
}

func SnakeToCapitalCamelCase(s string) string {
	words := strings.Split(s, "_")
	for i := range words {
		if len(words[i]) > 0 {
			runes := []rune(words[i])
			// Capitalize the first letter
			runes[0] = unicode.ToUpper(runes[0])
			// Lowercase the rest of the letters (optional, depends on specific need)
			for j := 1; j < len(runes); j++ {
				runes[j] = unicode.ToLower(runes[j])
			}
			words[i] = string(runes)
		}
	}
	return strings.Join(words, "")
}
