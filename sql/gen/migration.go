//go:build ignore

package main

import (
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strings"
	"text/template"
	"unicode"
)

type MigrationFiles []string

func (i *MigrationFiles) String() string {
	return fmt.Sprintf("%v", *i)
}
func (i *MigrationFiles) Set(value string) error {
	*i = append(*i, value)
	return nil
}

const tmpl = `// Code generated by migration.go; DO NOT EDIT.
package migrations

import (
	"context"
	"database/sql"
)

func Migrate{{.Name}}(ctx context.Context, db *sql.DB) error {
{{- range $index, $name := .MigrationNames}}
	if err := Migration{{$name}}(ctx, db); err != nil {
		return err
	}
{{- end}}
	return nil
}

{{range $index, $name := .MigrationNames}}
func Migration{{$name}}(ctx context.Context, db *sql.DB) error {
	tx, err := db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()

{{- range $stmt := index $.MigrationStatements $index}}
	if _, err := tx.ExecContext(ctx, ` + "`" + `{{$stmt}}` + "`" + `); err != nil {
		return err
	}
{{- end}}

	return tx.Commit()
}
{{end}}
`

type Config struct {
	Name                string
	MigrationNames      []string
	MigrationStatements [][]string
}

func main() {
	var migrations MigrationFiles
	name := flag.String("name", "", "Variable prefix")
	flag.Var(&migrations, "file", "SQL files for migration in order")
	flag.Parse()

	if name == nil || *name == "" {
		panic("Name is required")
	}

	for _, file := range migrations {
		if fileInfo, err := os.Stat(file); err != nil || fileInfo.IsDir() {
			panic("Invalid file: " + file)
		}
	}

	migrationNames := []string{}
	migrationStatements := [][]string{}
	for _, file := range migrations {
		content, _ := os.ReadFile(file)
		migrationStatements = append(migrationStatements, parseSQLStatements(string(content)))

		migrationNames = append(migrationNames, SnakeToCapitalCamelCase(FileToName(file)))
	}

	config := Config{
		Name:                SnakeToCapitalCamelCase(*name),
		MigrationNames:      migrationNames,
		MigrationStatements: migrationStatements,
	}

	outputPath := "migrations/z_" + strings.ToLower(*name) + "_gen.go"
	f, _ := os.Create(outputPath)
	defer f.Close()

	t := template.Must(template.New("migrations").Parse(tmpl))
	t.Execute(f, config)
	exec.Command("go", "fmt", outputPath).Run()
}
func parseSQLStatements(sql string) []string {
	// Regex splits by semicolon followed by optional whitespace and newline
	re := regexp.MustCompile(`(?m);(\s*)$`)
	raw := re.Split(sql, -1)

	var cleaned []string
	for _, s := range raw {
		if t := strings.TrimSpace(s); t != "" {
			cleaned = append(cleaned, t)
		}
	}
	return cleaned
}

func FileToName(path string) string {
	// 1. Get "gds.sql" from "asd/gds.sql"
	base := filepath.Base(path)

	// 2. Get ".sql" from "gds.sql"
	ext := filepath.Ext(base)

	// 3. Remove ".sql" from "gds.sql" to get "gds"
	name := strings.TrimSuffix(base, ext)

	return name
}

func SnakeToCapitalCamelCase(s string) string {
	words := strings.Split(s, "_")
	for i := range words {
		if len(words[i]) > 0 {
			runes := []rune(words[i])
			// Capitalize the first letter
			runes[0] = unicode.ToUpper(runes[0])
			// Lowercase the rest of the letters (optional, depends on specific need)
			for j := 1; j < len(runes); j++ {
				runes[j] = unicode.ToLower(runes[j])
			}
			words[i] = string(runes)
		}
	}
	return strings.Join(words, "")
}
