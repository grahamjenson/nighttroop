//go:build ignore

package main

import (
	"flag"
	"os"
	"regexp"
	"strings"
	"text/template"
	"unicode"
)

const tmpl = `// Code generated by migration.go; DO NOT EDIT.
package {{.Package}}

import "embed"

//go:embed {{.SourceFile}}
var {{.Name}}Raw embed.FS

// {{.Name}}Statements contains the parsed, ordered SQL statements
var {{.Name}}Statements = []string{
{{- range .Statements}}
	{{printf "%q" .}},
{{- end}}
}
`

func main() {
	name := flag.String("name", "Schema", "Variable prefix")
	file := flag.String("file", "", "SQL file to process")
	pkg := flag.String("pkg", "migrations", "Package name")
	flag.Parse()

	if *file == "" {
		flag.Usage()
		os.Exit(1)
	}

	content, _ := os.ReadFile(*file)

	// Regex splits by semicolon followed by optional whitespace and newline
	re := regexp.MustCompile(`(?m);(\s*)$`)
	raw := re.Split(string(content), -1)

	var cleaned []string
	for _, s := range raw {
		if t := strings.TrimSpace(s); t != "" {
			cleaned = append(cleaned, t)
		}
	}

	f, _ := os.Create(*pkg + "/z_" + strings.ToLower(*name) + "_gen.go")
	defer f.Close()

	t := template.Must(template.New("gen").Parse(tmpl))
	t.Execute(f, map[string]any{
		"Name":       *name,
		"SourceFile": *file,
		"Package":    *pkg,
		"Statements": cleaned,
	})
}

func SnakeToCapitalCamelCase(s string) string {
	words := strings.Split(s, "_")
	for i := range words {
		if len(words[i]) > 0 {
			runes := []rune(words[i])
			// Capitalize the first letter
			runes[0] = unicode.ToUpper(runes[0])
			// Lowercase the rest of the letters (optional, depends on specific need)
			for j := 1; j < len(runes); j++ {
				runes[j] = unicode.ToLower(runes[j])
			}
			words[i] = string(runes)
		}
	}
	return strings.Join(words, "")
}
