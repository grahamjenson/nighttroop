//go:build ignore

package main

import (
	"flag"
	"fmt"
	"os"
	"os/exec"
	"regexp"
	"strings"
	"text/template"

	"nighttroop.t1d.nz/utils"
)

const tmpl = `// Code generated by migration.go; DO NOT EDIT.
package migrations

import (
	"context"
	"database/sql"
	"fmt"
)

func Migrate{{.Name}}(ctx context.Context, db *sql.DB) error {

	_, err := db.Exec("CREATE TABLE IF NOT EXISTS schema_migrations (version TEXT NOT NULL PRIMARY KEY);")
	if (err != nil) {
		return fmt.Errorf("failed to create schema_migrations table: %w", err)
	}
	


{{- range $index, $name := .GetFileVars }}
	if err := Migration{{$name}}(ctx, db); err != nil {
		return err
	}
{{- end}}
	return nil
}

{{range $index, $name := .GetFileVars }}
func Migration{{$name}}(ctx context.Context, db *sql.DB) error {

	var versionSeen int;
	err  := db.QueryRow("SELECT COUNT(version) FROM schema_migrations WHERE version = ?;", "{{$name}}").Scan(&versionSeen)
	if err != nil {
		return err
	}
	if versionSeen > 0 {
		fmt.Printf("Migration %s already applied, skipping\n", "{{$name}}")
		return nil
	}
	fmt.Printf("Migration %s applying\n", "{{$name}}")

	tx, err := db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()

		{{- range $stmt := index $.MigrationStatements $index}}
			fmt.Printf("Running migration: %s\n", ` + "`" + `{{$stmt}}` + "`" + `)
			if _, err := tx.ExecContext(ctx, ` + "`" + `{{$stmt}}` + "`" + `); err != nil {
				return err
			}
		{{- end}}

	if _, err := tx.ExecContext(ctx, "INSERT INTO schema_migrations (version) VALUES (?);", "{{$name}}"); err != nil {
		return err
	}

	return tx.Commit()
}
{{end}}
`

type Config struct {
	Name                string
	Migrations          utils.FlagFileList
	MigrationStatements [][]string
}

func (c Config) GetFileVars() []string {
	var vars []string
	for _, filevars := range c.Migrations.GetFileVars() {
		vars = append(vars, filevars.VarName)
	}
	return vars
}

func main() {
	// TODO: store run migrations so they dont run again and again
	var migrations utils.FlagFileList
	name := flag.String("name", "", "Variable prefix")
	flag.Var(&migrations, "file", "SQL files for migration in order")
	flag.Parse()

	if name == nil || *name == "" {
		panic("Name is required")
	}

	for _, file := range migrations {
		if fileInfo, err := os.Stat(file); err != nil || fileInfo.IsDir() {
			panic("Invalid file: " + file)
		}
	}

	migrationStatements := [][]string{}
	for _, file := range migrations {
		content, _ := os.ReadFile(file)
		migrationStatements = append(migrationStatements, parseSQLStatements(string(content)))

	}

	config := Config{
		Name:                utils.SnakeToCapitalCamelCase(*name),
		Migrations:          migrations,
		MigrationStatements: migrationStatements,
	}

	outputPath := "migrations/z_" + strings.ToLower(*name) + "_gen.go"
	f, _ := os.Create(outputPath)
	defer f.Close()

	t := template.Must(template.New("migrations").Parse(tmpl))

	err := t.Execute(f, config)
	if err != nil {
		panic(fmt.Sprintf("Failed to execute template: %v", err))
	}

	exec.Command("go", "fmt", outputPath).Run()
}

func parseSQLStatements(sql string) []string {
	// Regex splits by semicolon followed by optional whitespace and newline
	re := regexp.MustCompile(`(?m);(\s*)$`)
	raw := re.Split(sql, -1)

	var cleaned []string
	for _, s := range raw {
		if t := strings.TrimSpace(s); t != "" {
			cleaned = append(cleaned, t)
		}
	}
	return cleaned
}
